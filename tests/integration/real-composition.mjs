/**
 * REAL-composition test: boot a genuine `cordis.yml` through the genuine
 * Cordis Loader, with every `@deepseek-ai/*` import resolved to real monorepo
 * source (see `scripts/setup-integration.mjs`), and prove the bridge works as
 * a deepseek-harness plugin:
 *
 *   - the Loader mounts `PythonBridgeService` (`ctx.pythonBridge`),
 *     `SystemPrompt`, `ToolRuntime` (`ctx.tools`), and the generated
 *     `MlService` (`ctx.ml`) honoring `static inject` ordering,
 *   - real schemastery applies the generated `static Config` to the
 *     cordis.yml row (defaults filled, camelCase keys),
 *   - `ctx.ml.embed()` executes against a real Python child process,
 *   - `resize_image` is retrievable from the real `ToolRuntime`,
 *   - a real `ctx.emit('session/event')` reaches the Python listener through
 *     the generated registration and the bridge's `event/deliver` channel,
 *   - `ctx.fiber.dispose()` runs the effect disposers and kills the child.
 *
 * Prerequisites (offline):
 *   node scripts/setup-integration.mjs
 * Run:
 *   node --experimental-strip-types tests/integration/real-composition.mjs
 */
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const integration = join(root, '.gen/integration')
const app = join(integration, 'app')
const monorepo = process.env.DSH_MONOREPO ?? '/home/chad/workspace/deepseek-harness'

process.env.PYTHONPATH = 'examples/python-bridge-ml:python/sdk-dsl/src'

let failures = 0
function assert(cond, message) {
  if (!cond) {
    failures++
    console.error(`FAIL: ${message}`)
  } else {
    console.log(`ok: ${message}`)
  }
}

function real(name) {
  return import(join(integration, 'node_modules', name, 'index.mjs'))
}

// ---------------------------------------------------------------------------
// 1. Generate the ML bridge package into the app directory.
// ---------------------------------------------------------------------------

const { generateBridgePackage } = await import(
  join(root, 'packages/bridge/python-bridge-codegen/src/index.ts')
)
const source = readFileSync(join(root, 'examples/python-bridge-ml/provider.py'), 'utf8')
const artifacts = generateBridgePackage({
  module: 'examples.python-bridge-ml.provider',
  packageName: '@my-org/python-bridge-ml',
  sources: [{ path: 'provider.py', contents: source }],
})
assert(artifacts.parsed.diagnostics.length === 0, 'no codegen diagnostics')

rmSync(app, { recursive: true, force: true })
for (const f of artifacts.files) {
  const p = join(app, 'python-bridge-ml', f.path)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, f.contents)
}

// ---------------------------------------------------------------------------
// 2. Write the composition cordis.yml and boot it through the real Loader.
// ---------------------------------------------------------------------------

const cordisYml = `# REAL-composition test composition (generated by the test).
- id: system-prompt
  name: '@deepseek-ai/dsh-system-prompt'

- id: tools
  name: '@deepseek-ai/dsh-tools'

- id: python-bridge
  name: '@peroxidess/dsh-python-bridge-runtime'

- id: ml
  name: './python-bridge-ml/src/index.ts'
  config:
    pythonBin: ${process.env.DSH_E2E_PYTHON ?? 'python3'}
    module: examples.python-bridge-ml.provider
    cwd: ${root}
    modelPath: /tmp/model
`
writeFileSync(join(app, 'cordis.yml'), cordisYml)

const { Context } = await real('@deepseek-ai/cordis')
const { default: Loader } = await real('@deepseek-ai/cordis-plugin-loader')
const { default: Include } = await real('@deepseek-ai/cordis-plugin-include')
const { default: Group } = await real('@deepseek-ai/cordis-plugin-group')

const ctx = new Context()
await ctx.plugin(Loader)
ctx.loader.builtins.include = Include
ctx.loader.builtins.group = Group

let bootError = null
try {
  await ctx.loader.create({
    id: 'include',
    name: 'cordis:include',
    config: { path: pathToFileURL(join(app, 'cordis.yml')).href },
  })
} catch (error) {
  bootError = error
}
assert(bootError === null, `cordis.yml booted through the real Loader${bootError ? ` (${bootError})` : ''}`)
if (bootError !== null) {
  const seen = new Set()
  const dump = (error, depth) => {
    if (!error || seen.has(error)) return
    seen.add(error)
    console.error(`${'  '.repeat(depth)}${error.constructor.name}: ${error.message}`)
    if (error.stack) console.error(error.stack.split('\n').slice(1, 4).map(l => `${'  '.repeat(depth)}  ${l.trim()}`).join('\n'))
    if (Array.isArray(error.errors)) for (const e of error.errors) dump(e, depth + 1)
    if (error.cause) dump(error.cause, depth + 1)
  }
  dump(bootError, 0)
  process.exit(1)
}

// ---------------------------------------------------------------------------
// 3. Assert the composition surface through the real registry.
// ---------------------------------------------------------------------------

for (let i = 0; i < 200; i++) {
  const ml = ctx.get('ml')
  if (ml !== undefined && ml.bridge?.ready) break
  await new Promise(r => setTimeout(r, 50))
}

const ml = ctx.get('ml')
assert(ml !== undefined, 'ctx.ml registered by the generated package through the Loader')
assert(ctx.get('pythonBridge') !== undefined, 'ctx.pythonBridge mounted')
assert(ctx.get('tools') !== undefined, 'ctx.tools mounted (real ToolRuntime)')

// Real schemastery applied the generated Config: cordis.yml supplied only
// modelPath (plus base keys); defaults must be filled by the zod schema.
assert(ml !== undefined && ml.bridge?.ready === true, 'generated service bridge became ready')

// 4. Typed service call against the real Python child.
const embedded = await ml.embed(['hello', 'loader'])
assert(Array.isArray(embedded) && embedded.length === 2 && embedded[0].length === 768,
  'ctx.ml.embed() returns 768-dim vectors via the real composition')

const classified = await ml.classify('aW1hZ2U=')
assert(Array.isArray(classified) && classified.length === 5,
  'ctx.ml.classify() uses the Python default top_k=5')

// 5. The module tool registered with the REAL ToolRuntime.
const tool = ctx.get('tools').get('resize_image')
assert(tool !== undefined, 'resize_image retrievable from the real ToolRuntime')

// 6. A real ctx.emit reaches the Python listener through the generated wiring.
const logs = []
ml.bridge.onLog(entry => logs.push(entry))
ctx.emit('session/event', { type: 'tool/call', data: { name: 'resize_image' } })
let auditSeen = false
for (let i = 0; i < 40 && !auditSeen; i++) {
  await new Promise(r => setTimeout(r, 50))
  auditSeen = logs.some(l => l.message.includes('audit'))
}
assert(auditSeen, `real ctx.emit('session/event') reached the Python listener (logs: ${JSON.stringify(logs)})`)

// 7. Fiber teardown runs the effect disposers: the Python child must exit.
await ctx.fiber.dispose()
assert(ml.bridge.ready === false, 'bridge torn down by fiber dispose')

if (failures > 0) {
  console.error(`${failures} real-composition check(s) failed`)
  process.exit(1)
}
console.log('ALL REAL-COMPOSITION CHECKS PASSED')
