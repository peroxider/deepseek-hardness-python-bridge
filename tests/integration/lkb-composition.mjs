/**
 * REAL-composition test for converting an external Python codebase (the LKB
 * Plan Graph from a ClawCodex checkout) into a dsh plugin: boot a genuine
 * `cordis.yml` mounting the generated `@my-org/lkb-bridge` package through
 * the genuine Cordis Loader, and drive the Plan Graph through `ctx.lkb` and
 * the real `ToolRuntime` against a real Python child and the real
 * file-backed LKB store.
 *
 * This is an EXAMPLE integration: the LKB source tree is external to this
 * repository, so the test skips cleanly when it is absent. Point
 * `LKB_SRC` at any checkout of the extension to run it elsewhere.
 *
 * Prerequisites (offline):
 *   node scripts/setup-integration.mjs
 * Run:
 *   LKB_SRC=/path/to/clawcodex/extensions/lkb/src \
 *     node --experimental-transform-types tests/integration/lkb-composition.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const lkbSrc = process.env.LKB_SRC ?? '/mnt/c/WorkSpace/clawcodex/extensions/lkb/src'

if (!existsSync(join(lkbSrc, 'lkb_dsh/bridge.py'))) {
  console.log(`SKIP: LKB source tree not found at ${lkbSrc} (set LKB_SRC to run this example)`)
  process.exit(0)
}

const integration = join(root, '.gen/integration')
const app = join(integration, 'lkb-app')

// The Python child imports lkb (external extension) + dsh_bridge.
process.env.PYTHONPATH = `${lkbSrc}:${join(root, 'python/sdk-dsl/src')}`

let failures = 0
function assert(cond, message) {
  if (!cond) {
    failures++
    console.error(`FAIL: ${message}`)
  } else {
    console.log(`ok: ${message}`)
  }
}

function real(name) {
  return import(join(integration, 'node_modules', name, 'index.mjs'))
}

// ---------------------------------------------------------------------------
// 1. Generate the LKB bridge package into the app directory.
// ---------------------------------------------------------------------------

const { generateBridgePackage } = await import(
  join(root, 'packages/bridge/python-bridge-codegen/src/index.ts')
)
const source = readFileSync(join(lkbSrc, 'lkb_dsh/bridge.py'), 'utf8')
const artifacts = generateBridgePackage({
  module: 'lkb_dsh.bridge',
  packageName: '@my-org/lkb-bridge',
  sources: [{ path: 'bridge.py', contents: source }],
})
assert(artifacts.parsed.diagnostics.length === 0, 'no codegen diagnostics')

rmSync(app, { recursive: true, force: true })
for (const f of artifacts.files) {
  const p = join(app, 'lkb-bridge', f.path)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, f.contents)
}

// ---------------------------------------------------------------------------
// 2. Boot the composition through the real Loader.
// ---------------------------------------------------------------------------

const lkbHome = mkdtempSync(join(tmpdir(), 'lkb-dsh-composition-'))
const cordisYml = `# REAL-composition test: LKB as a dsh plugin (generated by the test).
- id: system-prompt
  name: '@deepseek-ai/dsh-system-prompt'

- id: tools
  name: '@deepseek-ai/dsh-tools'

- id: python-bridge
  name: '@deepseek-ai/dsh-python-bridge-runtime'

- id: lkb
  name: './lkb-bridge/src/index.ts'
  config:
    pythonBin: ${process.env.DSH_E2E_PYTHON ?? 'python3'}
    module: lkb_dsh.bridge
    cwd: ${root}
    boardId: composition
    home: ${lkbHome}
`
writeFileSync(join(app, 'cordis.yml'), cordisYml)

const { Context } = await real('@deepseek-ai/cordis')
const { default: Loader } = await real('@deepseek-ai/cordis-plugin-loader')
const { default: Include } = await real('@deepseek-ai/cordis-plugin-include')
const { default: Group } = await real('@deepseek-ai/cordis-plugin-group')

const ctx = new Context()
await ctx.plugin(Loader)
ctx.loader.builtins.include = Include
ctx.loader.builtins.group = Group

let bootError = null
try {
  await ctx.loader.create({
    id: 'include',
    name: 'cordis:include',
    config: { path: pathToFileURL(join(app, 'cordis.yml')).href },
  })
} catch (error) {
  bootError = error
}
assert(bootError === null, `cordis.yml booted through the real Loader${bootError ? ` (${bootError})` : ''}`)
if (bootError !== null) {
  const seen = new Set()
  const dump = (error, depth) => {
    if (!error || seen.has(error)) return
    seen.add(error)
    console.error(`${'  '.repeat(depth)}${error.constructor.name}: ${error.message}`)
    if (Array.isArray(error.errors)) for (const e of error.errors) dump(e, depth + 1)
    if (error.cause) dump(error.cause, depth + 1)
  }
  dump(bootError, 0)
  process.exit(1)
}

for (let i = 0; i < 200; i++) {
  const lkb = ctx.get('lkb')
  if (lkb !== undefined && lkb.bridge?.ready) break
  await new Promise(r => setTimeout(r, 50))
}

const lkb = ctx.get('lkb')
assert(lkb !== undefined, 'ctx.lkb registered by the generated package through the Loader')
assert(lkb !== undefined && lkb.bridge?.ready === true, 'lkb bridge became ready')

// ---------------------------------------------------------------------------
// 3. Drive the Plan Graph through ctx.lkb (real LKB store).
// ---------------------------------------------------------------------------

const t1 = await lkb.create_task('upstream design')
assert(t1.decision === 'committed', `create_task committed (${t1.decision}: ${t1.reason})`)
const t2 = await lkb.create_task('downstream implementation')
assert(t2.decision === 'committed', 'second create_task committed')

const dep = await lkb.add_dependency(t2.task.id, t1.task.id)
assert(dep.decision === 'committed', 'add_dependency committed')

const listed = await lkb.list_tasks()
assert(Array.isArray(listed.tasks) && listed.tasks.length === 2, 'list_tasks returns both tasks')
const downstream = listed.tasks.find(t => t.subject === 'downstream implementation')
assert(downstream.derivedStatus === 'blocked', 'downstream derived as blocked before upstream completes')
assert(downstream.blockedBy.includes(t1.task.id), 'blockedBy edge projected')

// ---------------------------------------------------------------------------
// 4. Tools registered with the REAL ToolRuntime and executable.
// ---------------------------------------------------------------------------

const tools = ctx.get('tools')
for (const name of ['lkb_create_task', 'lkb_list_tasks', 'lkb_update_task', 'lkb_board_view']) {
  assert(tools.get(name) !== undefined, `${name} registered in the real ToolRuntime`)
}

const boardTool = tools.get('lkb_board_view')
const boardResult = await boardTool.execute({}, {})
const boardValue = boardResult?.value ?? boardResult
assert(boardValue !== undefined, 'lkb_board_view tool executed')

// Tool path: create + transition via the shared bridge (same Python child).
const created = await tools.get('lkb_create_task').execute({ subject: 'tool-created task' }, {})
const createdValue = created?.value ?? created
assert(createdValue?.task?.id?.startsWith('T-'), `tool-created task id (${JSON.stringify(createdValue).slice(0, 80)})`)

// ---------------------------------------------------------------------------
// 5. Lifecycle through the service: claim + start + complete flips derived state.
// ---------------------------------------------------------------------------

const started = await lkb.update_task(t1.task.id, 'in_progress')
assert(started.decision === 'committed', `update_task(in_progress) committed (${started.decision}: ${started.reason})`)
const completed = await lkb.update_task(t1.task.id, 'completed')
assert(completed.decision === 'committed', 'update_task(completed) committed')

const after = await lkb.list_tasks()
const downstreamAfter = after.tasks.find(t => t.subject === 'downstream implementation')
assert(downstreamAfter.derivedStatus === 'ready', 'downstream becomes ready after upstream completes')
assert(after.lkbBoard.counts.verified === 1, 'board counts one verified task')

// ---------------------------------------------------------------------------
// 6. Teardown.
// ---------------------------------------------------------------------------

await ctx.fiber.dispose()
assert(lkb.bridge.ready === false, 'bridge torn down by fiber dispose')
console.log(`(lkb store: ${lkbHome})`)

if (failures > 0) {
  console.error(`${failures} LKB-composition check(s) failed`)
  process.exit(1)
}
console.log('ALL LKB-COMPOSITION CHECKS PASSED')
